export function useDT() {
  const locale = useLocale();
  return (s: string) => dt(s, locale);
}
export const dt = (s: string, locale: "en" | "fr") => (locale === "fr" ? (UI[s] ?? CONTENT_FR[s] ?? translate(s, locale)) : s);
