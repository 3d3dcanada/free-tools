#!/usr/bin/env node
/**
 * Licence inventory of what ships in the build: every production dependency in package-lock.json
 * (dev tooling is not shipped and is left out), plus the bundled assets.
 *
 *   node scripts/licenses.mjs            write THIRD-PARTY-LICENSES.md
 *   node scripts/licenses.mjs --check    exit 1 if a package has no licence or one that needs review
 *
 * Read from the lockfile, with node_modules/<pkg>/package.json as the fallback, so run `npm ci` first.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const check = process.argv.includes("--check");

/** Licences that put no condition on this repository beyond keeping the notice. */
const PERMISSIVE = new Set([
  "MIT", "ISC", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "0BSD", "BlueOak-1.0.0", "CC0-1.0",
  "Unlicense", "OFL-1.1", "Python-2.0", "CC-BY-4.0", "Zlib", "MIT-0", "WTFPL",
]);
const ids = (expr) => expr.replace(/[()]/g, " ").split(/\s+(?:OR|AND|WITH)\s+|\s+/).filter(Boolean);
// "A OR B": fine if one option is permissive. "A AND B": every part must be.
const acceptable = (expr) => {
  const e = expr.trim();
  if (/\sOR\s/.test(e)) return e.split(/\s+OR\s+/).some(acceptable);
  return ids(e).every((i) => PERMISSIVE.has(i) || i === "AND" || i === "WITH");
};

const direct = new Set(Object.keys(pkg.dependencies ?? {}));
const rows = [];
for (const [key, entry] of Object.entries(lock.packages)) {
  if (!key.startsWith("node_modules/") || entry.dev) continue;
  const name = key.replace(/^.*node_modules\//, "");
  let license = entry.license;
  let homepage = "";
  const manifest = join(root, key, "package.json");
  if (existsSync(manifest)) {
    const m = JSON.parse(readFileSync(manifest, "utf8"));
    license ??= typeof m.license === "string" ? m.license : m.license?.type ?? (m.licenses ?? []).map((l) => l.type).join(" OR ");
    homepage = m.homepage ?? (typeof m.repository === "string" ? m.repository : m.repository?.url ?? "");
  }
  homepage = homepage.replace(/^git\+/, "").replace(/\.git$/, "").replace(/^git:\/\//, "https://");
  rows.push({ name, version: entry.version, license: license || "UNKNOWN", homepage, direct: direct.has(name), optional: !!entry.optional });
}
rows.sort((a, b) => a.name.localeCompare(b.name));

const counts = new Map();
for (const r of rows) counts.set(r.license, (counts.get(r.license) ?? 0) + 1);
const review = rows.filter((r) => !acceptable(r.license));

const ASSETS = [
  ["public/models/u2netp-webgl.onnx", "U²-Net-P background-removal model", "Apache-2.0", "Xuebin Qin and contributors; ONNX conversion by rembg; MaxPool padding rewritten by 3D3D (see public/models/README.txt)"],
  ["public/pdf-assets/ (code, cmaps, wasm)", "PDF.js static assets", "Apache-2.0, BSD-3-Clause, MIT", "Notices in each directory"],
  ["public/pdf-assets/standard_fonts/Liberation*", "Liberation Sans 2.1.5", "OFL-1.1", "Four unmodified files"],
  ["public/pdf-assets/standard_fonts/Foxit*", "Foxit standard fonts (PDFium)", "BSD-3-Clause", "Notice in standard_fonts/LICENSE_FOXIT"],
  ["public/pdf-assets/iccs/", "ICC profile", "CC0-1.0", ""],
  ["Geist, Geist Mono (via @fontsource-variable)", "Typefaces", "OFL-1.1", "Bundled by the build from the npm packages"],
  ["public/academy/diagrams/", "Lesson diagrams", "Apache-2.0", "Drawn for the academy by 3D3D"],
];

const out = [];
out.push("# Third-party licences", "");
out.push(
  "Generated by `npm run licenses` from `package-lock.json`. It lists what the production build can contain: every",
  "non-dev package in the lockfile, and the files bundled in `public/`. Build and test tooling (Vite, TypeScript, esbuild,",
  "React Router's CLI and their dependencies) is not shipped and is not listed.",
  "",
  `This repository's own code and content are Apache-2.0 (see \`LICENSE\`). ${rows.length} production packages:`,
  "",
  "| Licence | Packages |",
  "| --- | ---: |",
  ...[...counts].sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`),
  "",
);
out.push(
  review.length
    ? `**Needs review (${review.length}):** ${review.map((r) => `${r.name}@${r.version} (${r.license})`).join(", ")}`
    : "No package falls outside the permissive licences listed in `scripts/licenses.mjs`.",
  "",
);
out.push("## Bundled assets", "", "| Where | What | Licence | Note |", "| --- | --- | --- | --- |", ...ASSETS.map((a) => `| ${a.map((c) => c.replaceAll("|", "\\|")).join(" | ")} |`), "");
const dual = rows.filter((r) => /\sOR\s/.test(r.license));
if (dual.length) {
  out.push(
    "## Dual-licensed packages",
    "",
    "Each offers a choice. The permissive option is the one this build relies on.",
    "",
    "| Package | Offered | Taken |",
    "| --- | --- | --- |",
    ...dual.map((r) => {
      const options = r.license.replace(/[()]/g, "").split(/\s+OR\s+/);
      const taken = options.find((o) => PERMISSIVE.has(o.trim())) ?? options[0];
      return `| ${r.name}@${r.version} | ${r.license} | ${taken} |`;
    }),
    "",
  );
}
out.push("## Direct dependencies", "", "| Package | Version | Licence | Source |", "| --- | --- | --- | --- |");
for (const r of rows.filter((x) => x.direct)) out.push(`| ${r.name} | ${r.version} | ${r.license} | ${r.homepage} |`);
out.push("", "## Every production package", "", "| Package | Version | Licence |", "| --- | --- | --- |");
for (const r of rows) out.push(`| ${r.name}${r.optional ? " (optional)" : ""} | ${r.version} | ${r.license} |`);
out.push("");

if (!check) writeFileSync(join(root, "THIRD-PARTY-LICENSES.md"), out.join("\n"));
console.log(`licenses: ${rows.length} production packages, ${[...counts].map(([l, n]) => `${n} ${l}`).slice(0, 8).join(", ")}`);
if (review.length) {
  console.log(`licenses: ${review.length} need review`);
  for (const r of review) console.log(`  ${r.name}@${r.version}  ${r.license}`);
}
process.exit(check && review.length ? 1 : 0);
